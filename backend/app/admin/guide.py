"""«Гайд по управлению» — a built-in admin help page (issue #72 follow-up).

A single read-only page, reachable from its own sidebar tab and from the «Авто»
screens, that documents how to run the whole admin panel: the menu structure,
the single car form, the reference tables, the home content blocks, photos and
the catalog cache. Kept in sync with ``docs/card-composer.md``.
"""
from __future__ import annotations

from fastapi import Request
from fastapi.responses import RedirectResponse
from sqladmin import BaseView, expose

from app.admin.composer import _is_admin_session, _page


GUIDE_HTML = """
<div class="topbar"><a class="btn-link" href="/admin">← В админку</a></div>
<h1>Гайд по управлению админкой</h1>
<p class="hint">Как управлять каталогом и контентом сайта. Любое изменение сразу
попадает на сайт — кэш обновляется автоматически.</p>

<h2>Вход и доступ</h2>
<p>Панель — <code>/admin</code>. Доступ только у пользователей с флагом
<strong>is_admin</strong>. Логин и пароль создаются из переменных окружения
<code>ADMIN_EMAIL</code> / <code>ADMIN_PASSWORD</code> при старте сервиса. Пароль
существующего админа в панели не перезаписывается — меняйте его в самой панели.</p>

<h2>Структура меню</h2>
<ul>
  <li><strong>Главная</strong> — Баннеры главной, Наши подборки.</li>
  <li><strong>Каталог → Авто</strong> — все автомобили. Одна форма = одна
      карточка целиком.</li>
  <li><strong>Справочники</strong> — Бренд, Модель, Тип кузова, КПП, Привод,
      Тип двигателя, Цвет.</li>
</ul>
<p>Отдельных разделов «Сборщик», «Комплектации», «Фото», «Преимущества»,
«Подарки», «Характеристики» больше нет — всё это правится внутри карточки авто.</p>

<h2>Порядок работы (важно)</h2>
<p>Карточка авто только <strong>выбирает</strong> значения из справочников. Поэтому
сначала заведите нужное в <strong>Справочниках</strong>, а потом создавайте авто:</p>
<ol>
  <li>Бренд → Модель (модель привязана к бренду и обязательна для авто).</li>
  <li>Тип кузова, Тип двигателя, КПП, Привод, Цвета.</li>
  <li>Создаёте авто и выбираете эти значения из списков.</li>
</ol>

<h2>Каталог → Авто</h2>
<p>Список — таблица: ID, авто (бренд + модель, slug), состояние, видимость
(<span class="tag tag-on">На сайте</span> / <span class="tag tag-off">Скрыто</span>),
цена, количество. В каждой строке: <strong>Редактировать</strong>,
<strong>Скрыть/Показать</strong>, <strong>Удалить</strong>. Кнопка
<strong>«+ Создать авто»</strong> открывает пустую форму.</p>

<h3>Форма авто (создание = редактирование)</h3>
<p>Страница повторяет публичную карточку сверху вниз. Созданное авто
<strong>сразу публикуется</strong> (если не скрыто) — черновиков нет.</p>
<ul>
  <li><strong>Основное:</strong> slug (адрес <code>/car/{slug}</code>, уникальный),
      состояние (Новое / С пробегом), модель (обязательна), тип кузова и двигателя,
      цена и старая цена, бейдж выгоды, статус-текст, спеки героя (мощность,
      расход/запас, разгон, макс. скорость), год и пробег (для авто с пробегом),
      количество, в наличии, промо. Пустые поля на сайте не отображаются.</li>
  <li><strong>Фото для каталога:</strong> превью-карточка в каталоге (независимо
      от баннеров цветов и галереи). Размер <strong>1000×750 px (4:3)</strong>.</li>
  <li><strong>Цвета и баннеры:</strong> отметьте минимум <strong>один</strong> цвет
      из справочника и к каждому отмеченному цвету загрузите свой баннер
      (<strong>1440×480 px, 3:1</strong>). Большой баннер вверху карточки — это
      картинка выбранного цвета (1 цвет = 1 картинка); переключение цвета меняет
      баннер.</li>
  <li><strong>Комплектации:</strong> название, объём, мощность, КПП, привод, цена и
      цена со скидкой, порядок, а также <strong>своё фото</strong> для каждой
      комплектации (<strong>640×360 px, 16:9</strong>; показывается в её блоке на
      странице авто). Добавить — заполнить пустую строку внизу (минимум название).
      Удалить — галочка «удалить».</li>
  <li><strong>Преимущества (чипы героя):</strong> иконка
      (percent / trade / gift / shield), текст, порядок, чекбокс «активно».
      Неактивные на сайт не выводятся.</li>
  <li><strong>Подарки:</strong> текст + порядок.</li>
  <li><strong>Характеристики:</strong> три блока — Безопасность / Экстерьер /
      Интерьер. Каждая строка — один пункт.</li>
  <li><strong>Фото:</strong> у существующих — порядок, «главное» (radio), «удалить».
      «Добавить фото» — один или несколько файлов; встанут после текущих. Если
      главное не выбрано — им станет первое фото.</li>
</ul>
<p>Кнопка <strong>«Создать авто»</strong> / <strong>«Сохранить»</strong> сохраняет
карточку целиком. Ссылка <strong>«Открыть на сайте»</strong> ведёт на готовую
страницу.</p>

<h3>Скрыть / показать / удалить</h3>
<ul>
  <li><strong>Скрыть с сайта</strong> — авто исчезает из каталога, списков, похожих
      и подборок главной, а <code>/car/{slug}</code> отдаёт 404. Бронь и заявка по
      скрытому авто запрещены.</li>
  <li><strong>Показать на сайте</strong> — возвращает обратно.</li>
  <li><strong>Удалить</strong> — удаляет авто целиком вместе с комплектациями,
      фото, преимуществами и т.д. Действие необратимо.</li>
</ul>

<h2>Справочники</h2>
<ul>
  <li><strong>Бренд</strong> — название, slug, логотип (загрузка файла в хранилище).</li>
  <li><strong>Модель</strong> — привязана к бренду; slug уникален в пределах бренда.</li>
  <li><strong>Тип кузова / КПП / Привод / Тип двигателя</strong> — название + slug.</li>
  <li><strong>Цвет</strong> — название + HEX (например <code>#262626</code>).</li>
</ul>
<p>Удалять значение, которое уже используется в авто, не стоит — сначала смените
его в карточках. Новое значение, добавленное здесь, сразу появляется в списках
формы авто.</p>

<h2>Главная</h2>
<ul>
  <li><strong>Баннеры главной</strong> — слайды героя: только <strong>картинка</strong>
      (<strong>1440×480 px, 3:1</strong>) + ссылка (на какую страницу ведёт баннер
      при клике), активность, порядок. Текст и кнопки не настраиваются — всё на
      самой картинке.</li>
  <li><strong>Наши подборки</strong> — карточки-подборки: заголовок, описание,
      кнопка, картинка, опциональная привязка к авто, активность, порядок.
      Подборка со скрытым авто на сайте не показывается.</li>
</ul>

<h2>Фото и хранилище</h2>
<p>Загруженные файлы (логотипы брендов, фото авто, картинки баннеров/подборок)
складываются в объектное хранилище (MinIO/S3). В таблицах хранится ключ объекта,
а на сайте отдаётся публичная ссылка.</p>

<h2>Кэш каталога</h2>
<p>Публичный API кэшируется. Любое сохранение в админке (авто, справочники,
главная) сбрасывает кэш, поэтому свежие данные видны на сайте сразу — отдельной
кнопки «обновить» не нужно.</p>

<h2>Частые вопросы</h2>
<ul>
  <li><strong>Создал авто — оно сразу на сайте?</strong> Да. Чтобы убрать —
      нажмите «Скрыть с сайта».</li>
  <li><strong>Slug занят.</strong> Форма не даст сохранить — выберите другой slug.</li>
  <li><strong>Нужного значения нет в списке.</strong> Добавьте его в Справочниках
      и вернитесь в карточку.</li>
  <li><strong>Пустой блок на карточке.</strong> Пустые поля и блоки не
      отображаются — это нормально.</li>
</ul>
"""


class GuideView(BaseView):
    name = "Гайд по управлению"
    icon = "fa-solid fa-book"

    @expose("/guide", methods=["GET"], identity="guide")
    async def guide(self, request: Request):
        if not await _is_admin_session(request):
            return RedirectResponse(url="/admin/login", status_code=302)
        return _page(GUIDE_HTML)
